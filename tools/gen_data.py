#!/usr/bin/env python3
"""Generate the site's drill + chain data files from the REAL AgentTrace
drill store. Nothing here is hand-typed: event rows, beat positions,
per-producer counts and the cost total are all derived from
agent-trace/drill/output/trace-drill-45d404d0/store.jsonl, and the script
asserts the known totals (117 events, $0.57313) before writing anything.
"""
import json
from pathlib import Path

STORE = Path(__file__).resolve().parents[2] / "agent-trace" / "drill" / "output" / "trace-drill-45d404d0" / "store.jsonl"
OUT = Path(__file__).resolve().parents[1] / "data"

events = [json.loads(l) for l in STORE.read_text().splitlines() if l.strip()]
assert len(events) == 117, len(events)

def first(source, type_):
    return next((e for e in events if e["source"] == source and e["type"] == type_), None)

def kill_seam(br_events):
    # mirrors agenttrace.query._kill_seam: a step_started whose
    # (action, resource) step was already started - the step in flight
    # when the executor was killed, replayed on resume.
    seen = set()
    for e in br_events:
        if e["type"] == "step_started":
            key = (e["payload"].get("action"), e["payload"].get("resource"))
            if key in seen:
                return e
            seen.add(key)
    return None

br = [e for e in events if e["source"] == "blast-radius"]
seam = kill_seam(br)
resume_ev = next(e for e in br if e["seq"] > seam["seq"] and e["type"] == "step_applied")

BEATS = [
    ("block",    "BLOCK",       first("agent-canary", "compare_verdict")),
    ("flagged",  "FLAGGED",     first("agent-gate", "screening_findings")),
    ("plan",     "PLAN",        first("blast-radius", "plan_created")),
    ("kill",     "KILL -9",     seam),
    ("resume",   "RESUME",      resume_ev),
    ("rollback", "ROLLBACK",    first("blast-radius", "rollback_step_skipped")),
    ("answered", "ANSWERED",    first("factory-floor-agent", "outcome")),
    ("costed",   "COSTED",      first("agent-ledger", "span")),
    ("matrix",   "MATRIX DONE", first("agent-chaos", "chaos_report")),
]
assert all(ev for _, _, ev in BEATS)

def label(e):
    p = e.get("payload") or {}
    t = e["type"]
    if e["source"] == "agent-canary" and t == "decision_record":
        return "decision: BLOCK promotion"
    if t == "compare_verdict":
        return "verdict: candidate blocked (success 100% -> 36%)"
    if t == "screening_findings":
        return "screening: 6 patterns flagged"
    if t == "decision_record" and e["source"] == "agent-gate":
        return "decision: allow (policy)"
    if t == "decision_record" and e["source"] == "factory-floor-agent":
        return "decision: grounded - answer"
    if e["source"] == "blast-radius":
        if t == "step_started":  return f"step started: {p.get('action', '')} {p.get('resource', '')}".strip()
        if t == "step_applied":  return f"step applied: {p.get('action', '')} {p.get('resource', '')}".strip()
        if t == "rollback_step": return "rollback step applied"
        if t == "verify_failed": return "verification FAILED - bad disk"
        if t == "run_finished":  return "run finished: rolled back"
        return t.replace("_", " ")
    if e["source"] == "agent-ledger":
        return f"span: {p.get('name', t)}"
    if e["source"] == "agent-chaos":
        return "chaos report: silent failures 100% -> 0%" if t == "chaos_report" else t.replace("_", " ")
    if e["source"] == "factory-floor-agent":
        return {"run_start": "run started", "plan": "plan: concept lookup",
                "retrieval": "retrieval: passages found", "groundedness": "groundedness check",
                "outcome": "outcome: answered (grounded)", "run_end": "run ended"}.get(t, t)
    return t.replace("_", " ")

rows, total = [], 0.0
for e in events:
    cost = 0.0
    if e["source"] == "agent-ledger":
        a = e["payload"].get("attributes", {})
        if a.get("agentledger.kind") == "step":
            cost = float(a.get("agentledger.cost_usd", 0.0))
    total += cost
    rows.append({"seq": e["seq"], "src": e["source"], "type": e["type"],
                 "label": label(e), "cost": round(cost, 6)})
assert round(total, 5) == 0.57313, round(total, 5)

from collections import Counter
counts = Counter(e["source"] for e in events)

drill = {
    "traceId": events[0]["trace_id"],
    "totalEvents": len(events),
    "totalCost": round(total, 5),
    "producerCounts": dict(counts),
    "beats": [{"key": k, "label": l, "atSeq": ev["seq"]} for k, l, ev in BEATS],
    "events": rows,
}
OUT.mkdir(exist_ok=True)
(OUT / "drill.js").write_text(
    "/* Generated by tools/gen_data.py from the real drill store - do not hand-edit. */\n"
    "window.DRILL = " + json.dumps(drill, indent=1) + ";\n")

# Tamper demo: the first 8 events of the same store, as raw JSONL lines,
# so the browser parser sees the exact original bytes (number literals
# included) and the chain verifies standalone from the genesis hash.
raw_lines = [l for l in STORE.read_text().splitlines() if l.strip()][:8]
assert json.loads(raw_lines[0])["prev_hash"] == "0" * 64
(OUT / "chain.js").write_text(
    "/* Generated by tools/gen_data.py: seqs 1-8 of the real drill store, raw. */\n"
    "window.CHAIN_EVENTS = " + json.dumps(raw_lines) + ";\n"
    "window.CHAIN_FULL_COUNT = 117;\n")

print("beats:", [(b["label"], b["atSeq"]) for b in drill["beats"]])
print("producer counts:", dict(counts))
print("total cost:", drill["totalCost"])
print("wrote", OUT / "drill.js", "and", OUT / "chain.js")
